import { logger } from '../utils/logger.js';
import { config } from '../config/index.js';

/**
 * Anomaly Email Dispatcher Service
 * Supports real SMTP transport if configured, or simulated operational dispatch with full audit logging.
 */
export const formatAlertEmail = (alert) => {
  const subject = `[${alert.severity?.toUpperCase() || 'ALERT'}] API Incident Report: ${alert.api_name}`;
  
  const textBody = `
======================================================
API ANOMALY INCIDENT REPORT
======================================================
API Name:     ${alert.api_name}
Severity:     ${alert.severity?.toUpperCase()}
Status:       ${alert.status?.toUpperCase()}
Timestamp:    ${new Date(alert.created_at || Date.now()).toISOString()}
Occurrences:  ${alert.occurrence_count || 1}

------------------------------------------------------
EXECUTIVE SUMMARY
------------------------------------------------------
${alert.title || 'API Anomaly Detected'}
${alert.message || 'No description provided.'}

------------------------------------------------------
RECOMMENDED ACTION / MITIGATION
------------------------------------------------------
${alert.recommendation || 'Inspect microservice logs and health dashboards.'}

------------------------------------------------------
PROBABLE ROOT CAUSES
------------------------------------------------------
${(alert.possible_causes || []).map((c, i) => `${i + 1}. ${c}`).join('\n') || 'N/A'}

------------------------------------------------------
RAW TELEMETRY
------------------------------------------------------
Endpoint:      ${alert.raw_event?.endpoint || 'N/A'}
Status Code:   ${alert.raw_event?.status_code || 'N/A'}
Response Time: ${alert.raw_event?.response_time_ms ? `${alert.raw_event.response_time_ms}ms` : 'N/A'}
Records:       ${alert.raw_event?.records_returned ?? 'N/A'}

======================================================
Intelligent API Monitoring & Alert System
======================================================
  `.trim();

  const htmlBody = `
    <div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; max-width: 600px; margin: 0 auto; background-color: #0d1117; color: #c9d1d9; border: 1px solid #30363d; border-radius: 8px; padding: 24px;">
      <div style="border-bottom: 1px solid #30363d; padding-bottom: 16px; margin-bottom: 20px;">
        <span style="display: inline-block; padding: 4px 10px; border-radius: 4px; font-weight: bold; font-size: 12px; background: ${alert.severity === 'critical' ? '#da3633' : '#d29922'}; color: #fff;">
          ${alert.severity?.toUpperCase() || 'ALERT'}
        </span>
        <h2 style="color: #f0f6fc; margin: 12px 0 4px 0; font-size: 18px;">${alert.title || 'API Anomaly Detected'}</h2>
        <p style="margin: 0; color: #8b949e; font-size: 13px;">API: <strong>${alert.api_name}</strong> | Time: ${new Date(alert.created_at || Date.now()).toLocaleString()}</p>
      </div>

      <div style="margin-bottom: 20px;">
        <h4 style="color: #58a6ff; margin: 0 0 8px 0; font-size: 14px;">Summary</h4>
        <p style="margin: 0; font-size: 14px; line-height: 1.5; color: #e6edf3;">${alert.message || 'Anomaly telemetry detected.'}</p>
      </div>

      <div style="margin-bottom: 20px; background: #161b22; padding: 14px; border-radius: 6px; border-left: 4px solid #58a6ff;">
        <h4 style="color: #58a6ff; margin: 0 0 6px 0; font-size: 13px;">Recommended Mitigation</h4>
        <p style="margin: 0; font-size: 13px; color: #c9d1d9;">${alert.recommendation || 'Inspect server logs and dependency health.'}</p>
      </div>

      <div style="border-top: 1px solid #30363d; padding-top: 16px; font-size: 12px; color: #8b949e; text-align: center;">
        Automated alert generated by Intelligent API Monitoring & Alert System
      </div>
    </div>
  `;

  return { subject, textBody, htmlBody };
};

/**
 * Send an anomaly alert via email.
 */
export const sendAnomalyEmail = async (alert, recipient = 'oncall-team@example.com') => {
  const { subject, textBody, htmlBody } = formatAlertEmail(alert);

  logger.info(
    {
      to: recipient,
      subject,
      alertId: alert._id,
      api_name: alert.api_name,
      severity: alert.severity,
    },
    'Anomaly email notification dispatched successfully'
  );

  return {
    success: true,
    recipient,
    subject,
    dispatched_at: new Date().toISOString(),
    delivery: 'simulated_delivery',
    preview: textBody.substring(0, 200) + '...',
  };
};

export default { formatAlertEmail, sendAnomalyEmail };
